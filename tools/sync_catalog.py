"""Regenerate hooks/catalog.ts from skills/adv/assets/models.json.

The mod (hooks/register.ts) cannot import JSON, so it reads the model catalog
from a generated TypeScript module. Run this after editing models.json:

    python tools/sync_catalog.py          # rewrite hooks/catalog.ts
    python tools/sync_catalog.py --check  # exit 1 if it is out of date (CI)
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "skills" / "adv" / "assets" / "models.json"
TARGET = ROOT / "hooks" / "catalog.ts"

HEADER = (
    "// GENERATED by tools/sync_catalog.py from skills/adv/assets/models.json. Do not edit.\n"
    "// Run `python tools/sync_catalog.py` after changing models.json.\n"
)


def render(catalog: dict) -> str:
    body = json.dumps(catalog, indent=2, ensure_ascii=False)
    return f"{HEADER}\nexport const CATALOG = {body} as const\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if catalog.ts is stale")
    args = parser.parse_args(argv)

    expected = render(json.loads(SOURCE.read_text(encoding="utf-8")))
    current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else None

    if args.check:
        if current != expected:
            print(f"{TARGET.relative_to(ROOT)} is out of date; run tools/sync_catalog.py")
            return 1
        return 0

    if current != expected:
        TARGET.write_text(expected, encoding="utf-8", newline="\n")
        print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
